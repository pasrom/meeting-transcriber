import Foundation
@testable import MeetingTranscriber

/// Mock protocol generator that captures the transcript instead of calling Claude CLI.
class MockProtocolGen: ProtocolGenerating {
    var generateCalled = false
    var capturedTranscript: String?
    var capturedTitle: String?
    // swiftlint:disable:next discouraged_optional_boolean
    var capturedDiarized: Bool?
    var capturedMeetingStartTime: Date?
    var capturedInstructions: ProtocolInstructions?
    var shouldThrow = false
    /// The title the model puts in the heading. Unset, it echoes the title it
    /// was given, which cannot tell a heading the model wrote from the input.
    var headingTitle: String?
    /// Runs inside `generate`, i.e. after the transcript is saved and before the
    /// queue names the protocol: the moment a test can change the disk under it.
    var onGenerate: (() -> Void)?

    func generate(
        transcript: String, title: String, diarized: Bool, meetingStartTime: Date?, instructions: ProtocolInstructions,
    ) throws -> String {
        generateCalled = true
        onGenerate?()
        capturedTranscript = transcript
        capturedTitle = title
        capturedDiarized = diarized
        capturedMeetingStartTime = meetingStartTime
        capturedInstructions = instructions
        if shouldThrow {
            throw NSError(
                domain: "MockProtocolGen",
                code: 1,
                userInfo: [NSLocalizedDescriptionKey: "Mock protocol error"],
            )
        }
        return """
        # Meeting Protocol - \(headingTitle ?? title)
        **Date:** 2026-03-06

        ---

        ## Summary
        Test protocol generated by mock.
        """
    }
}

/// The call shape from before meeting-notes templates, for tests that are not
/// about the template: the built-in one, and no meeting start unless given.
extension ProtocolGenerating {
    func generate(transcript: String, title: String, diarized: Bool, meetingStartTime: Date? = nil) async throws -> String {
        try await generate(
            transcript: transcript, title: title, diarized: diarized, meetingStartTime: meetingStartTime,
            instructions: ProtocolInstructions(template: ProtocolGenerator.protocolPrompt),
        )
    }
}
